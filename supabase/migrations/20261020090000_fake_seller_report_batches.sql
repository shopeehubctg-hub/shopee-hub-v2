-- Weekly fake-seller link lists. Unknown brands cannot be imported until mapped.
create table public.fake_seller_brands (
  id bigint generated by default as identity primary key,
  tenant_id text not null references public.tenants(id),
  brand_key text not null,
  brand_name text not null,
  store_id text not null references public.stores(id),
  created_at timestamptz not null default now(),
  unique (tenant_id, brand_key, store_id),
  foreign key (tenant_id, store_id) references public.stores(tenant_id, id)
);
create table public.fake_seller_report_batches (
  id bigint generated by default as identity primary key,
  tenant_id text not null references public.tenants(id),
  store_id text not null references public.stores(id),
  brand_name text not null,
  source_file_id text not null,
  report_date date not null,
  uploaded_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique (source_file_id, store_id),
  foreign key (tenant_id, store_id) references public.stores(tenant_id, id)
);
create index fake_seller_batch_tenant_date_idx on public.fake_seller_report_batches(tenant_id,report_date);
create table public.fake_seller_report_links (
  id bigint generated by default as identity primary key,
  tenant_id text not null references public.tenants(id),
  store_id text not null references public.stores(id),
  batch_id bigint not null references public.fake_seller_report_batches(id),
  report_date date not null,
  url text not null,
  canonical_url text not null,
  created_at timestamptz not null default now(),
  unique (store_id,report_date,canonical_url),
  foreign key (tenant_id, store_id) references public.stores(tenant_id, id)
);
create index fake_seller_link_tenant_date_idx on public.fake_seller_report_links(tenant_id,report_date);
alter table public.fake_seller_brands enable row level security;
alter table public.fake_seller_report_batches enable row level security;
alter table public.fake_seller_report_links enable row level security;
revoke all on public.fake_seller_brands,public.fake_seller_report_batches,public.fake_seller_report_links from anon,authenticated;
grant select on public.fake_seller_brands,public.fake_seller_report_batches,public.fake_seller_report_links to service_role;
grant insert on public.fake_seller_report_batches,public.fake_seller_report_links to service_role;
grant usage,select on sequence public.fake_seller_report_batches_id_seq,public.fake_seller_report_links_id_seq to service_role;
