begin;

alter table public.user_module_permissions add column if not exists additive_grant boolean not null default false;

create table if not exists public.feature_grant_notifications(
 id bigint generated by default as identity primary key,
 tenant_id text not null references public.tenants(id),
 user_id bigint not null references public.customer_users(id) on delete cascade,
 module_id text not null,
 audit_id uuid not null references public.user_access_audit_log(id),
 granted_at timestamptz not null default now(),
 acknowledged_at timestamptz,
 constraint feature_grant_notifications_audit_module_key unique(audit_id,module_id)
);
create index if not exists feature_grant_notifications_pending_idx on public.feature_grant_notifications(tenant_id,user_id,acknowledged_at,granted_at);
alter table public.feature_grant_notifications enable row level security;

create or replace function public.permission_effective_modules(p_tenant text,p_user_id bigint) returns text[]
language sql security invoker set search_path='' as $$
 with member as(select * from public.customer_users where id=p_user_id and tenant_id=p_tenant),
 modules(id) as(select unnest(array['overview','design','calculator','packages','advertising','orders','health','protection','live_calendar','actions','overview_leaderboard','overview_leaderboard_all_stores','overview_store_sales'])),
 base as(
  select m.id from member u cross join modules m where m.id not like 'overview_%' and(
   u.role='superadmin'
   or exists(select 1 from public.user_module_permissions p where p.user_id=u.id and p.module_id=m.id and p.enabled and p.additive_grant)
   or (u.module_access_mode='custom' and exists(select 1 from public.user_module_permissions p where p.user_id=u.id and p.module_id=m.id and p.enabled and not p.additive_grant))
   or (u.module_access_mode='role_default' and case when m.id='live_calendar' then exists(select 1 from public.tenant_module_permissions t where t.tenant_id=p_tenant and t.module_id=m.id and t.enabled) else not exists(select 1 from public.tenant_module_permissions t where t.tenant_id=p_tenant and t.module_id=m.id and not t.enabled) end)
  )
 ), sections as(
  select m.id from member u cross join modules m where m.id like 'overview_%' and(
   u.role='superadmin' or(
    exists(select 1 from base where id='overview')
    and not exists(select 1 from public.tenant_module_permissions t where t.tenant_id=p_tenant and t.module_id='overview' and not t.enabled)
    and case when m.id='overview_leaderboard_all_stores' then
      u.module_access_mode='custom' and exists(select 1 from public.user_module_permissions p where p.user_id=u.id and p.module_id=m.id and p.enabled and not p.additive_grant)
      and exists(select 1 from public.user_module_permissions p where p.user_id=u.id and p.module_id='overview_leaderboard' and p.enabled)
    else exists(select 1 from public.user_module_permissions p where p.user_id=u.id and p.module_id=m.id and p.enabled and (p.additive_grant or u.module_access_mode='custom')) end
   )
  )
 ) select coalesce(array_agg(id order by id),array[]::text[]) from(select id from base union all select id from sections)x
$$;

create or replace function public.clear_revoked_additive_grant() returns trigger language plpgsql security invoker set search_path='' as $$
begin if old.additive_grant and not new.enabled then new.additive_grant:=false;end if;return new;end $$;
create or replace trigger user_module_permission_clear_revoked_additive before update on public.user_module_permissions for each row execute function public.clear_revoked_additive_grant();

create or replace function public.notify_new_feature_grants() returns trigger language plpgsql security invoker set search_path='' as $$
declare v text;
begin
 for v in select value#>>'{}' from jsonb_array_elements(coalesce(new.after_value->'enabledModules','[]'::jsonb)) value
          except select value#>>'{}' from jsonb_array_elements(coalesce(new.before_value->'enabledModules','[]'::jsonb)) value loop
  if v<>'overview_leaderboard_all_stores' then insert into public.feature_grant_notifications(tenant_id,user_id,module_id,audit_id,granted_at) values(new.tenant_id,new.target_user_id,v,new.id,new.created_at) on conflict do nothing;end if;
 end loop;return new;
end $$;
create or replace trigger user_access_audit_notify_features after insert on public.user_access_audit_log for each row execute function public.notify_new_feature_grants();

create or replace function public.grant_feature_to_all(p_tenant text,p_actor text,p_module text,p_request_id uuid) returns jsonb
language plpgsql security invoker set search_path='' as $$
declare actor public.customer_users;target public.customer_users;prior public.user_access_audit_log;before_modules text[];after_modules text[];deps text[];m text;before_value jsonb;after_value jsonb;child_id uuid;result jsonb;granted int:=0;skipped int:=0;already_enabled int:=0;
begin
 if p_tenant is null or p_actor is null or p_request_id is null or p_module is null or not(p_module=any(array['overview','design','calculator','packages','advertising','orders','health','protection','live_calendar','actions','overview_leaderboard','overview_store_sales'])) then raise exception 'PERMISSION_INVALID';end if;
 perform pg_advisory_xact_lock(hashtext(p_tenant),hashtext('user-access-write'));
 if not exists(select 1 from public.tenants where id=p_tenant and active) then raise exception 'PERMISSION_ACCESS_DENIED';end if;
 select * into actor from public.customer_users where tenant_id=p_tenant and email=lower(p_actor) for share;
 if not found or not actor.active or actor.role<>'superadmin' then raise exception 'PERMISSION_ACCESS_DENIED';end if;
 select * into prior from public.user_access_audit_log where tenant_id=p_tenant and request_id=p_request_id;
 if found then if prior.request_payload is distinct from jsonb_build_object('operation','grant_feature_to_all','actor',lower(p_actor),'module',p_module) then raise exception 'PERMISSION_REQUEST_CONFLICT';end if;return prior.result;end if;
 deps:=case when p_module in('overview_leaderboard','overview_store_sales') then array['overview',p_module] else array[p_module] end;
 for target in select * from public.customer_users where tenant_id=p_tenant and active and role<>'superadmin' order by id for update loop
  before_modules:=public.permission_effective_modules(p_tenant,target.id);
  if p_module=any(before_modules) then already_enabled:=already_enabled+1;continue;end if;
  if p_module in('live_calendar','overview_store_sales') and (target.store_access_mode<>'selected' or cardinality(public.permission_effective_stores(p_tenant,target.id))=0) then skipped:=skipped+1;continue;end if;
  if p_module='overview_leaderboard' and target.store_access_mode='selected' and cardinality(public.permission_effective_stores(p_tenant,target.id))=0 then skipped:=skipped+1;continue;end if;
  before_value:=jsonb_build_object('enabledModules',before_modules,'permissionsVersion',target.permissions_version::text);
  foreach m in array deps loop
   insert into public.user_module_permissions(user_id,module_id,enabled,additive_grant,updated_at) values(target.id,m,true,true,now())
   on conflict(user_id,module_id) do update set enabled=true,additive_grant=true,updated_at=excluded.updated_at;
  end loop;
  update public.customer_users set permissions_version=permissions_version+1 where id=target.id;
  after_modules:=public.permission_effective_modules(p_tenant,target.id);
  if not(p_module=any(after_modules)) or ('overview_leaderboard_all_stores'=any(after_modules) and not('overview_leaderboard_all_stores'=any(before_modules))) then raise exception 'PERMISSION_SCOPE';end if;
  after_value:=jsonb_build_object('enabledModules',after_modules,'permissionsVersion',(target.permissions_version+1)::text);
  child_id:=gen_random_uuid();
  insert into public.user_access_audit_log(id,tenant_id,actor_user_id,target_user_id,actor_email,request_id,request_payload,before_value,after_value,result)
  values(child_id,p_tenant,actor.id,target.id,lower(p_actor),gen_random_uuid(),jsonb_build_object('operation','grant_feature_to_all_member','module',p_module,'rootRequestId',p_request_id),before_value,after_value,jsonb_build_object('id',target.id,'version',(target.permissions_version+1)::text));
  granted:=granted+1;
 end loop;
 result:=jsonb_build_object('granted',granted,'skipped',skipped,'alreadyEnabled',already_enabled);
 insert into public.user_access_audit_log(tenant_id,actor_user_id,target_user_id,actor_email,request_id,request_payload,before_value,after_value,result)
 values(p_tenant,actor.id,actor.id,lower(p_actor),p_request_id,jsonb_build_object('operation','grant_feature_to_all','actor',lower(p_actor),'module',p_module),jsonb_build_object('operation','grant_feature_to_all'),jsonb_build_object('operation','grant_feature_to_all'),result);
 return result;
end $$;

create or replace function public.ack_feature_grant_notifications(p_tenant text,p_user_id bigint,p_ids bigint[]) returns jsonb
language plpgsql security invoker set search_path='' as $$
declare affected int;
begin
 if p_tenant is null or p_user_id is null or p_ids is null or cardinality(p_ids) not between 1 and 20 or exists(select 1 from unnest(p_ids)x where x is null or x<1) then raise exception 'PERMISSION_INVALID';end if;
 if not exists(select 1 from public.tenants where id=p_tenant and active) then raise exception 'PERMISSION_ACCESS_DENIED';end if;
 if not exists(select 1 from public.customer_users where id=p_user_id and tenant_id=p_tenant and active) then raise exception 'PERMISSION_ACCESS_DENIED';end if;
 update public.feature_grant_notifications set acknowledged_at=coalesce(acknowledged_at,now()) where tenant_id=p_tenant and user_id=p_user_id and id=any(p_ids) and acknowledged_at is null;
 get diagnostics affected=row_count;return jsonb_build_object('acknowledged',affected);
end $$;

revoke all on table public.feature_grant_notifications from public,anon,authenticated,service_role;
grant select,insert on table public.feature_grant_notifications to service_role;
grant update(acknowledged_at) on table public.feature_grant_notifications to service_role;
grant usage,select on sequence public.feature_grant_notifications_id_seq to service_role;
revoke all on function public.clear_revoked_additive_grant(),public.notify_new_feature_grants(),public.grant_feature_to_all(text,text,text,uuid),public.ack_feature_grant_notifications(text,bigint,bigint[]) from public,anon,authenticated;
grant execute on function public.permission_effective_modules(text,bigint),public.grant_feature_to_all(text,text,text,uuid),public.ack_feature_grant_notifications(text,bigint,bigint[]) to service_role;

commit;
