create table public.sales_daily (
 id bigint generated by default as identity primary key,
 tenant_id text not null references public.tenants(id),
 report_date date not null,
 platform text not null check (platform in ('all','Shopee','Lazada','TikTok')),
 gross_revenue numeric(14,2) not null default 0,
 mtd_gross_revenue numeric(14,2),
 currency text not null default 'MYR',
 source text not null default 'BigSeller',
 synced_at timestamptz not null default now(),
 unique(tenant_id,report_date,platform)
);
create table public.sales_monthly_targets (
 tenant_id text not null references public.tenants(id),
 month date not null check(extract(day from month)=1),
 target numeric(14,2) not null check(target>0),
 updated_at timestamptz not null default now(),
 primary key(tenant_id,month)
);
alter table public.sales_daily enable row level security;
alter table public.sales_monthly_targets enable row level security;
create view public.sales_overview_daily with (security_invoker=true) as  WITH p AS (
         SELECT sales_daily.tenant_id,
            sales_daily.report_date,
            max(sales_daily.gross_revenue) FILTER (WHERE sales_daily.platform = 'all'::text) AS day_all,
            max(sales_daily.gross_revenue) FILTER (WHERE sales_daily.platform = 'Shopee'::text) AS day_shopee,
            max(sales_daily.gross_revenue) FILTER (WHERE sales_daily.platform = 'Lazada'::text) AS day_lazada,
            max(sales_daily.gross_revenue) FILTER (WHERE sales_daily.platform = 'TikTok'::text) AS day_tiktok,
            max(sales_daily.mtd_gross_revenue) FILTER (WHERE sales_daily.platform = 'all'::text) AS mtd_all,
            max(sales_daily.mtd_gross_revenue) FILTER (WHERE sales_daily.platform = 'Shopee'::text) AS mtd_shopee,
            max(sales_daily.mtd_gross_revenue) FILTER (WHERE sales_daily.platform = 'Lazada'::text) AS mtd_lazada,
            max(sales_daily.mtd_gross_revenue) FILTER (WHERE sales_daily.platform = 'TikTok'::text) AS mtd_tiktok,
            max(sales_daily.synced_at) AS synced_at
           FROM sales_daily
          GROUP BY sales_daily.tenant_id, sales_daily.report_date
        ), c AS (
         SELECT p.tenant_id,
            p.report_date,
            p.day_all,
            p.day_shopee,
            p.day_lazada,
            p.day_tiktok,
            p.mtd_all,
            p.mtd_shopee,
            p.mtd_lazada,
            p.mtd_tiktok,
            p.synced_at,
            EXTRACT(day FROM p.report_date)::integer AS day_of_month,
            EXTRACT(day FROM date_trunc('month'::text, p.report_date::timestamp with time zone) + '1 mon -1 days'::interval)::integer AS days_in_month,
            ( SELECT t.target
                   FROM sales_monthly_targets t
                  WHERE t.tenant_id = p.tenant_id AND t.month <= date_trunc('month'::text, p.report_date::timestamp with time zone)::date
                  ORDER BY t.month DESC
                 LIMIT 1) AS target
           FROM p
        )
 SELECT tenant_id,
    report_date,
    day_all,
    day_shopee,
    day_lazada,
    day_tiktok,
    mtd_all,
    mtd_shopee,
    mtd_lazada,
    mtd_tiktok,
    synced_at,
    day_of_month,
    days_in_month,
    target,
    days_in_month - day_of_month AS days_remaining,
    round(mtd_all / day_of_month::numeric * days_in_month::numeric, 2) AS estimated_monthly,
    round(target - mtd_all, 2) AS sales_difference,
        CASE
            WHEN days_in_month > day_of_month THEN round((target - mtd_all) / (days_in_month - day_of_month)::numeric, 2)
            ELSE NULL::numeric
        END AS daily_sales_target,
    round(mtd_all / NULLIF(target, 0::numeric) * 100::numeric, 2) AS target_progress_pct
   FROM c;
revoke all on public.sales_daily,public.sales_monthly_targets,public.sales_overview_daily from public,anon,authenticated,service_role;
grant select on public.sales_daily,public.sales_monthly_targets,public.sales_overview_daily to service_role;